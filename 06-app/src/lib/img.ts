/**
 * Уменьшенная копия фото с нашего сервера: `/files/:id?w=` отдаёт WebP нужной ширины (сервер делает 240, 480, 960 —
 * `IMAGE_WIDTHS` в 07-server/src/files.ts). Оригиналы весят 0,3–0,6 МБ, каталог на мобильном интернете грузился долго.
 * Ширина — с запасом на экран 3×: 240 — превью в списках и плитки, 480 — карточка каталога, 960 — галерея и баннер.
 * Чужие адреса и картинки моков возвращаются как есть.
 */
export const sized = (url: string | null | undefined, w: 240 | 480 | 960) =>
  url && /\/files\/[\w-]+(\?|$)/.test(url) ? url + (url.includes('?') ? '&' : '?') + 'w=' + w : url ?? '';
